from pathlib import Path
import json, re

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "prototype-assets/viewer/animation-data.json"
OUT = ROOT / "native-prototype/generated-audio-events.h"
ENUM_ALIASES = {"Hurts": "Hurt"}
# Names are the exported Mario/DAT141 sounds staged for the Vita external data folder.
AVAILABLE = {
    "mario_cape_hit", "MarioVictory", "mario_win2_pt2", "mario_win2",
    "mario_uspecCoin2", "mario_uspecCoin", "mario_uspec", "mario_Usmash",
    "mario_tauntSide", "mario_star", "mario_spin", "mario_sleep", "mario_runstop",
    "mario_runstart", "mario_otto", "mario_landLight", "mario_landAttack",
    "mario_kickswing", "mario_jumpsfx", "mario_jump2sfx", "mario_jump2",
    "mario_hurtBad2", "mario_hurtBad", "mario_hurt2", "mario_hoo", "mario_hoo_old",
    "mario_heavyLand", "mario_grunt4", "mario_grunt3", "mario_grunt2", "mario_grunt1",
    "mario_grow2", "mario_grow1", "mario_fsready", "mario_Fsmash_sfx", "mario_Fsmash",
    "mario_footstep2", "mario_footstep", "mario_fireballspawn", "mario_fireballsfx",
    "mario_fireballLand", "mario_finale", "mario_final2", "mario_final", "letsago",
    "mario_edgegrab", "mario_dspec6", "mario_dspec5", "mario_dspec4", "mario_dspec3",
    "mario_dspec2", "mario_dspec", "mario_Dsmash", "mario_dizzy", "mario_dead2",
    "mario_dead", "mario_charge", "mario_capespawn", "mario_cape", "mario_bthrow",
    "mario_backjump", "mario_yoohoo", "MarioDTauntSpin", "brawl_swing_s",
    "brawl_swing_m", "brawl_swing_l", "grab_swing4", "grab_swing6", "throw_woosh",
    "brawl_kick_l",
}
ALIASES = {
    "mario_lightLand": "mario_landLight",
    "mario_landHeavy": "mario_heavyLand",
    "mario_kick_l": "brawl_kick_l",
}

doc = json.loads(DATA.read_text(encoding="utf-8"))
events = set()
for anim in doc["animations"]:
    enum_name = ENUM_ALIASES.get(anim["name"], anim["name"])
    for frame_number, frame in enumerate(anim.get("frames", []), start=1):
        source = frame.get("eventSource", "")
        for sound in re.findall(r'this\.self\.playSound\("([^"]+)"', source):
            if sound.startswith("metal_"):
                continue  # Mario is not in the Metal character variant.
            sound = ALIASES.get(sound, sound)
            if sound not in AVAILABLE:
                continue
            events.add((enum_name, frame_number - 1, sound))

rows = sorted(events)
header = [
    "// Generated by generate-audio-events.py from animation-data.json eventSource.",
    "#pragma once",
    "struct AuthoredAudioEvent {int anim; int frame; const char* sound;};",
    "inline constexpr AuthoredAudioEvent AUTHORED_AUDIO_EVENTS[] = {",
]
header.extend(f' {{ssf::{anim},{frame},"{sound}"}},' for anim, frame, sound in rows)
header.append("};")
OUT.write_text("\n".join(header) + "\n", encoding="utf-8")
print(f"Wrote {len(rows)} authored sound events to {OUT}")
